export function formatReportForSharing(report) {
  const { statistics, aiAnalysis, sources } = report;
  
  let message = `📊 POST ANALYSIS REPORT\n`;
  message += `━━━━━━━━━━━━━━━━━━━━\n\n`;
  
  message += `📝 Content Statistics\n`;
  message += `━━━━━━━━━━━━━━━━━━━━\n`;
  message += `• Words: ${statistics.words}\n`;
  message += `• Characters: ${statistics.characters}\n`;
  message += `• Sentences: ${statistics.sentences}\n`;
  message += `• Paragraphs: ${statistics.paragraphs}\n`;
  message += `• Reading Time: ${statistics.readingTime} min\n\n`;
  
  message += `🤖 AI Analysis\n`;
  message += `━━━━━━━━━━━━━━━━━━━━\n`;
  message += `• AI Likelihood: ${aiAnalysis.score}%\n`;
  message += `• Assessment: ${aiAnalysis.assessment}\n`;
  message += `• Confidence: ${aiAnalysis.confidence}\n\n`;
  
  if (sources.length > 0) {
    message += `🔍 Possible Sources\n`;
    message += `━━━━━━━━━━━━━━━━━━━━\n`;
    message += `• Sources Found: ${sources.length}\n`;
    sources.forEach((source, index) => {
      message += `• ${source.title} (${source.similarity}%)\n`;
    });
  } else {
    message += `🔍 No sources found\n`;
  }
  
  message += `\n⚠️ Disclaimer: AI detection is probabilistic and not definitive proof of AI usage.\n`;
  message += `\nGenerated by Post Analyzer`;
  
  return message;
}

